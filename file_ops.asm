.MODEL SMALL
.STACK 100H

.DATA
FNAME DB 'TEST.TXT',0
MSG DB 'HELLO MASM'
LEN EQU $-MSG
HANDLE DW ?

.CODE
MAIN PROC
    MOV AX, @DATA
    MOV DS, AX

    MOV AH, 3CH
    MOV CX, 0
    LEA DX, FNAME
    INT 21H
    JC EXIT

    MOV HANDLE, AX

    MOV AH, 40H
    MOV BX, HANDLE
    MOV CX, LEN
    LEA DX, MSG
    INT 21H

    MOV AH, 3EH
    MOV BX, HANDLE
    INT 21H

EXIT:
    MOV AH, 4CH
    INT 21H
MAIN ENDP
END MAIN